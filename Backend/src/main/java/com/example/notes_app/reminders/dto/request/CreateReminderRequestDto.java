package com.example.notes_app.reminders.dto.request;

import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@NoArgsConstructor
@AllArgsConstructor
public class CreateReminderRequestDto {
    private long userId;
    private String title;
    private String remindAt; // YYYY-MM-DDTHH:mm:ss
    private String dueDate; // YYYY-MM-DD
    private String dueTime; // HH:mm
    private String category;
    private String status; // PENDING, COMPLETED, REJECTED, MISSED
    private String repeatInterval; // NONE, DAILY, WEEKLY, MONTHLY

    /** REM-07: first occurrence of a repeating series (wall clock). Defaults to remindAt. */
    private String startAt;

    /** FE-03: idempotency key generated by the app (a UUID). Optional for old clients. */
    @Size(max = 36, message = "clientId must be at most 36 characters")
    private String clientId;
}
